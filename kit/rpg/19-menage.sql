SET SCHEMA VOTREBIB;

BEGIN
  DECLARE V_ABSENT INTEGER DEFAULT 0;
  DECLARE CONTINUE HANDLER FOR SQLEXCEPTION SET V_ABSENT = 1;  -- ce qui manque déjà est ignoré
  DROP TABLE T_APPELS;
  DROP TABLE T_PGMREF;
  DROP FUNCTION F_TARIF_RPG3;
  DROP PROCEDURE PS_TRAITER_DEVIS;
  DROP PROCEDURE PS_GEN_FACT;
  DROP PROCEDURE PS_VAL_DEVIS;
  DROP PROCEDURE PS_CALC_TARIF_ADELIA;
  DROP PROCEDURE PS_CALC_TARIF_RPGLE;
  DROP PROCEDURE PS_CALC_TARIF_RPG3;
  DROP TABLE T_COMPARE;
  DROP TABLE T_CAS;
  DROP VIEW V_DEVIS;
  DROP TABLE FACTURE;
  DROP TABLE DEVLIG;
  DROP TABLE DEVIS;
  DROP TABLE COMPTEUR;
  DROP TABLE CLIENT;
  FOR P AS SELECT OBJNAME FROM TABLE (QSYS2.OBJECT_STATISTICS(CURRENT SCHEMA, '*PGM')) X
            WHERE OBJNAME IN ('CALCTAR3', 'CALCTARIF', 'CTLENCOURS', 'CALCTARA',
                              'CALCDEVIS', 'VALDEVIS', 'GENFACT')
  DO
    CALL QSYS2.QCMDEXC('DLTPGM PGM(' CONCAT CURRENT SCHEMA CONCAT '/' CONCAT P.OBJNAME CONCAT ')');
  END FOR;
  CALL QSYS2.QCMDEXC('DLTDTAQ DTAQ(' CONCAT CURRENT SCHEMA CONCAT '/EVT_CLIENT)');  -- si 17 s'est arrêté en route
  CALL QSYS2.QCMDEXC('DLTF FILE(' CONCAT CURRENT SCHEMA CONCAT '/KITRPGSRC)');
  CALL QSYS2.QCMDEXC('DLTF FILE(' CONCAT CURRENT SCHEMA CONCAT '/KITRPGLSRC)');
END;

BEGIN
  IF EXISTS (SELECT 1 FROM TABLE (QSYS2.OBJECT_STATISTICS(CURRENT SCHEMA, '*JRNRCV')) R
              WHERE R.OBJNAME LIKE 'KITRCV%') THEN
    CALL QSYS2.QCMDEXC('DLTJRN JRN(' CONCAT CURRENT SCHEMA CONCAT '/QSQJRN)');
    FOR R AS SELECT OBJNAME FROM TABLE (QSYS2.OBJECT_STATISTICS(CURRENT SCHEMA, '*JRNRCV')) X
              WHERE OBJNAME LIKE 'KITRCV%'
    DO
      CALL QSYS2.QCMDEXC('DLTJRNRCV JRNRCV(' CONCAT CURRENT SCHEMA CONCAT '/' CONCAT R.OBJNAME
                         CONCAT ') DLTOPT(*IGNINQMSG)');
    END FOR;
  END IF;
END;

-- Ce qui reste dans la bibliothèque
SELECT OBJNAME, OBJTYPE FROM TABLE (QSYS2.OBJECT_STATISTICS(CURRENT SCHEMA, '*ALL')) X
 ORDER BY OBJTYPE, OBJNAME;
